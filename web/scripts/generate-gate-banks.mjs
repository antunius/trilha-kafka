import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const outRoot = path.resolve(here, "../data/gates");

function item(q, correct, wrongs, w, tag) {
  return { q, o: [correct, wrongs[0], wrongs[1], wrongs[2]], a: 0, w, t: tag };
}

function cap(s) {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

function stemsFor(f) {
  if (Array.isArray(f.qs) && f.qs.length) return f.qs;
  return [
    `Sobre ${f.tag}: qual afirmação está certa?`,
    `Qual frase sobre ${f.tag} está certa?`,
    `${cap(f.tag)} — o que acontece de verdade?`,
    `Marque a leitura correta (${f.tag}).`,
    `Corrija o mito sobre ${f.tag}.`,
    `No caderno, a respeito de ${f.tag}: qual vale?`,
    `Se perguntarem ${f.tag} na mesa, qual frase é a verdadeira?`,
  ];
}

function pickWrongs(f, pool, wi) {
  if (Array.isArray(f.wrongs) && f.wrongs.length >= 3) {
    return f.wrongs.slice(0, 3);
  }
  return [
    pool[wi % pool.length],
    pool[(wi + 1) % pool.length],
    pool[(wi + 3) % pool.length],
  ];
}

function bank(name, facts, wrongs) {
  const questions = [];
  const seen = new Set();
  let wi = 0;
  for (const f of facts) {
    for (const q of stemsFor(f)) {
      if (seen.has(q)) continue;
      seen.add(q);
      questions.push(item(q, f.c, pickWrongs(f, wrongs, wi), f.w, f.tag));
      wi += 1;
    }
  }
  if (questions.length < 100) {
    throw new Error(`${name}: only ${questions.length} questions`);
  }
  return questions.slice(0, 108);
}

function write(track, slug, questions) {
  const dir = path.join(outRoot, track);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(
    path.join(dir, `${slug}.json`),
    JSON.stringify({ questions }, null, 2) + "\n",
  );
}

